                Política de privacidad de MiFincaInvent
            </h2>

            <p class="mb-8 text-sm text-gray-500">
                Última actualización: 11 de noviembre de 2026
            </p>

            <p class="mb-6 leading-7">
                Esta política de privacidad se aplica al uso de MiFincaInvent
                (https://inventario-0qli.onrender.com). Su finalidad es informar
                a los usuarios sobre los datos personales que pueden ser
                recopilados y tratados durante el uso de la aplicación,
                las finalidades de dicho tratamiento y los derechos que les
                asisten, de conformidad con la legislación colombiana sobre
                protección de datos personales, especialmente la Ley 1581 de
                2012 y sus normas reglamentarias.
            </p>

            <section class="mb-8">
                <h3 class="mb-3 text-xl font-bold text-emerald-800">
                    1. Responsable del tratamiento y contacto
                </h3>

                <p class="mb-3 leading-7">
                    MiFincaInvent es una aplicación web independiente destinada
                    a la gestión y administración de inventarios, administrada
                    desde Colombia.
                </p>

                <p class="mb-3 leading-7">
                    El responsable del tratamiento de los datos personales es
                    la persona natural que administra la aplicación y determina
                    las finalidades y los medios del tratamiento de la información.
                </p>

                <p class="leading-7">
                    Para consultas, solicitudes o inquietudes relacionadas con
                    la privacidad y el tratamiento de datos personales, los
                    usuarios pueden comunicarse mediante:
                    <a href="mailto:soporte.mifincainvent@gmail.com"
                        class="text-emerald-700 underline">
                        soporte.mifincainvent@gmail.com
                    </a>.
                </p>
            </section>

            <section class="mb-8">
                <h3 class="mb-3 text-xl font-bold text-emerald-800">
                    2. Datos personales recopilados y finalidades del tratamiento
                </h3>

                <p class="mb-3 leading-7">
                    MiFincaInvent puede recopilar y tratar información
                    proporcionada directamente por los usuarios durante la
                    utilización de la aplicación, incluyendo:
                </p>

                <ul class="mb-4 list-disc space-y-2 pl-6">
                    <li>Dirección de correo electrónico.</li>
                    <li>Contraseñas almacenadas mediante mecanismos de protección criptográfica.</li>
                    <li>Información relacionada con el perfil y la cuenta del usuario.</li>
                    <li>Información de inventarios, productos, registros y demás datos introducidos en la aplicación.</li>
                    <li>Fotografías, documentos y otros archivos que los usuarios decidan cargar.</li>
                    <li>Información técnica relacionada con el acceso y funcionamiento de la aplicación.</li>
                </ul>

                <p class="mb-3 leading-7">
                    Los datos se utilizan para crear y administrar cuentas,
                    permitir el inicio de sesión, gestionar inventarios,
                    productos y registros, administrar fotografías y documentos,
                    mantener la seguridad de las cuentas, atender consultas
                    técnicas y mejorar el funcionamiento de la aplicación.
                </p>

                <p class="leading-7">
                    Actualmente, la creación de cuentas es realizada por un
                    usuario con rol de superadministrador (superadmin).
                    No existe un formulario de registro público. Actualmente
                    no se implementa un procedimiento de verificación de la
                    dirección de correo electrónico.
                </p>
            </section>

            <section class="mb-8">
                <h3 class="mb-3 text-xl font-bold text-emerald-800">
                    3. Alojamiento y servicios de terceros
                </h3>

                <p class="mb-3 leading-7">
                    La aplicación está alojada en Render.com, proveedor de
                    infraestructura y alojamiento de aplicaciones web.
                </p>

                <p class="mb-3 leading-7">
                    La información estructurada de la aplicación se almacena
                    en TiDB Cloud, proveedor externo de servicios de bases
                    de datos en la nube.
                </p>

                <p class="leading-7">
                    Estos proveedores pueden procesar información necesaria
                    para prestar sus servicios, de acuerdo con sus respectivas
                    condiciones de servicio y políticas de privacidad.
                    El uso de infraestructura externa puede implicar el
                    procesamiento o almacenamiento de información fuera
                    de Colombia, dependiendo de la configuración de los servicios.
                </p>
            </section>

            <section class="mb-8">
                <h3 class="mb-3 text-xl font-bold text-emerald-800">
                    4. Registros técnicos y archivos de registro
                </h3>

                <p class="mb-3 leading-7">
                    Durante el acceso y utilización del sitio web pueden
                    generarse registros técnicos relacionados con las
                    solicitudes realizadas al servidor y el funcionamiento
                    de la aplicación.
                </p>

                <p class="mb-3 leading-7">
                    Estos registros pueden incluir direcciones IP, fecha y
                    hora de las solicitudes, información del navegador,
                    sistema operativo, rutas consultadas y datos necesarios
                    para diagnosticar problemas técnicos.
                </p>

                <p class="leading-7">
                    Esta información puede utilizarse para mantener el
                    funcionamiento de la aplicación, detectar errores,
                    investigar incidentes de seguridad y prevenir actividades
                    no autorizadas.
                </p>
            </section>

            <section class="mb-8">
                <h3 class="mb-3 text-xl font-bold text-emerald-800">
                    5. Cookies y tecnologías de seguimiento
                </h3>

                <p class="mb-3 leading-7">
                    MiFincaInvent puede utilizar cookies técnicas o de sesión
                    necesarias para el funcionamiento de la aplicación,
                    la autenticación de usuarios, la seguridad y la gestión
                    de las sesiones.
                </p>

                <p class="mb-3 leading-7">
                    La aplicación utiliza Cloudflare Web Analytics para
                    recopilar estadísticas generales de visitas y rendimiento
                    del sitio web, como información relacionada con el tráfico
                    y las páginas consultadas.
                </p>

                <p class="mb-3 leading-7">
                    Cloudflare Web Analytics utiliza una tecnología de
                    medición basada en JavaScript y no requiere cookies
                    de seguimiento ni almacenamiento local del navegador
                    para recopilar estas estadísticas.
                </p>

                <p class="leading-7">
                    Según la configuración actual, no se utilizan cookies
                    publicitarias ni tecnologías destinadas a mostrar
                    publicidad personalizada.
                </p>
            </section>

            <section class="mb-8">
                <h3 class="mb-3 text-xl font-bold text-emerald-800">
                    6. Fotografías, documentos y archivos cargados por los usuarios
                </h3>

                <p class="mb-3 leading-7">
                    MiFincaInvent permite cargar fotografías, documentos
                    y otros archivos relacionados con las funcionalidades
                    de gestión de inventarios.
                </p>

                <p class="mb-3 leading-7">
                    Estos archivos pueden contener información personal.
                    Los usuarios deben asegurarse de contar con los derechos
                    o autorizaciones necesarios para proporcionar información
                    de terceros.
                </p>

                <p class="leading-7">
                    Los archivos se utilizan para las funcionalidades de la
                    aplicación, como registrar, consultar, identificar y
                    administrar información relacionada con los inventarios.
                    Los usuarios deben evitar cargar información sensible
                    que no sea necesaria para utilizar MiFincaInvent.
                </p>
            </section>

            <section class="mb-8">
                <h3 class="mb-3 text-xl font-bold text-emerald-800">
                    7. Derechos de los titulares de los datos personales
                </h3>

                <p class="mb-3 leading-7">
                    De conformidad con la Ley 1581 de 2012, los titulares
                    tienen derecho a conocer, actualizar y rectificar sus
                    datos personales; solicitar prueba de la autorización
                    cuando corresponda; ser informados sobre el uso dado
                    a sus datos; presentar consultas y reclamaciones;
                    solicitar la supresión de sus datos o revocar la
                    autorización cuando sea procedente; y acceder
                    gratuitamente a sus datos personales objeto de tratamiento.
                </p>

                <p class="leading-7">
                    Los titulares también pueden solicitar la supresión
                    de sus datos personales mediante el correo electrónico
                    <a href="mailto:soporte.mifincainvent@gmail.com"
                        class="text-emerald-700 underline">
                        soporte.mifincainvent@gmail.com
                    </a>,
                    conforme a las condiciones y excepciones establecidas
                    en la legislación aplicable.
                </p>
            </section>

            <section class="mb-8">
                <h3 class="mb-3 text-xl font-bold text-emerald-800">
                    8. Autoridad de protección de datos personales
                </h3>

                <p class="mb-3 leading-7">
                    En Colombia, la Superintendencia de Industria y Comercio
                    (SIC) es la autoridad encargada de vigilar el cumplimiento
                    de las disposiciones relacionadas con la protección
                    de datos personales.
                </p>

                <p class="leading-7">
                    Los titulares podrán presentar reclamaciones ante dicha
                    entidad cuando consideren que sus derechos han sido
                    vulnerados, una vez agotado el trámite correspondiente.
                </p>

                <a href="https://www.sic.gov.co/"
                    target="_blank"
                    rel="noopener noreferrer"
                    class="text-emerald-700 underline">
                    Sitio web oficial de la SIC
                </a>
            </section>

            <section class="mb-8">
                <h3 class="mb-3 text-xl font-bold text-emerald-800">
                    9. Conservación y eliminación de los datos
                </h3>

                <p class="mb-3 leading-7">
                    Los datos personales se conservarán durante el tiempo
                    necesario para cumplir las finalidades para las cuales
                    fueron recopilados y mientras la cuenta del usuario
                    permanezca activa, cuando corresponda.
                </p>

                <p class="mb-3 leading-7">
                    La eliminación de las cuentas de usuario es realizada
                    por un usuario autorizado con el rol de superadministrador
                    (superadmin), mediante las funcionalidades administrativas
                    disponibles en MiFincaInvent.
                </p>

                <p class="mb-3 leading-7">
                    Los usuarios que deseen eliminar su cuenta o solicitar
                    la supresión de sus datos personales pueden comunicarse
                    mediante el correo electrónico
                    <a href="mailto:soporte.mifincainvent@gmail.com"
                        class="text-emerald-700 underline">
                        soporte.mifincainvent@gmail.com
                    </a>.
                </p>

                <p class="leading-7">
                    Cuando se elimine una cuenta, la información asociada
                    será eliminada de acuerdo con el funcionamiento de la
                    aplicación, salvo aquella que deba conservarse por
                    obligaciones legales o contractuales.
                </p>
            </section>

            <section class="mb-8">
                <h3 class="mb-3 text-xl font-bold text-emerald-800">
                    10. Servicios externos y fuentes de información
                </h3>

                <p class="mb-3 leading-7">
                    MiFincaInvent puede utilizar servicios y API de terceros,
                    como los servicios de consulta de información del
                    Departamento Administrativo Nacional de Estadística
                    (DANE), para obtener información pública y complementar
                    determinadas funcionalidades de la aplicación.
                </p>

                <p class="leading-7">
                    El uso de estos servicios se encuentra sujeto a las
                    condiciones y políticas de los respectivos proveedores.
                    La utilización de estas API no implica necesariamente
                    que se compartan datos personales de los usuarios.
                </p>
            </section>

            <section class="mb-8">
                <h3 class="mb-3 text-xl font-bold text-emerald-800">
                    11. Seguridad de la información
                </h3>

                <p class="mb-3 leading-7">
                    MiFincaInvent implementa medidas técnicas y organizativas
                    destinadas a proteger la información almacenada y
                    prevenir accesos no autorizados, pérdida, alteración
                    o divulgación indebida de los datos personales.
                </p>

                <p class="mb-3 leading-7">
                    Estas medidas pueden incluir mecanismos de autenticación,
                    protección de contraseñas, control de acceso, protección
                    de sesiones y utilización de servicios de infraestructura
                    en la nube.
                </p>

                <p class="leading-7">
                    Aunque se adoptan medidas de seguridad razonables,
                    ningún sistema informático puede garantizar una
                    protección absoluta frente a todos los riesgos existentes.
                </p>
